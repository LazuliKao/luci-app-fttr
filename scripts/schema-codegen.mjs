import ts from "typescript";

// Consume the SDK's deliberately small TypeScript wire language. Never turn an
// unrecognised construct into unknown: a new generator construct needs support.
export function renderSchemas(source) {
	const file = ts.createSourceFile("types.ts", source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
	if (file.parseDiagnostics.length) throw new Error("Invalid SDK TypeScript");
	const aliases = new Map();
	for (const node of file.statements) {
		if (!ts.isTypeAliasDeclaration(node) || node.typeParameters?.length) {
			throw new Error(`Unsupported SDK declaration: ${node.getText(file)}`);
		}
		if (aliases.has(node.name.text)) throw new Error(`Duplicate SDK type: ${node.name.text}`);
		aliases.set(node.name.text, node.type);
	}
	const rendered = new Map();
	const visiting = new Set();
	function fail(node) {
		throw new Error(`Unsupported SDK type: ${node.getText(file)}`);
	}
	function reference(name) {
		if (!aliases.has(name)) throw new Error(`Unknown SDK type: ${name}`);
		if (visiting.has(name)) throw new Error(`Recursive SDK type: ${name}`);
		if (!rendered.has(name)) {
			visiting.add(name);
			const expression = schema(aliases.get(name));
			visiting.delete(name);
			rendered.set(name, expression);
		}
		return `${name}Schema`;
	}
	function schema(node) {
		switch (node.kind) {
			case ts.SyntaxKind.StringKeyword:
				return "z.string()";
			case ts.SyntaxKind.NumberKeyword:
				return "z.number()";
			case ts.SyntaxKind.BooleanKeyword:
				return "z.boolean()";
			case ts.SyntaxKind.UnknownKeyword:
				return "z.unknown()";
			case ts.SyntaxKind.NeverKeyword:
				return "z.never()";
		}
		if (ts.isParenthesizedTypeNode(node)) return schema(node.type);
		if (ts.isLiteralTypeNode(node)) {
			if (node.literal.kind === ts.SyntaxKind.NullKeyword) return "z.null()";
			if (ts.isStringLiteral(node.literal)) return `z.literal(${JSON.stringify(node.literal.text)})`;
			if (
				[ts.SyntaxKind.TrueKeyword, ts.SyntaxKind.FalseKeyword].includes(node.literal.kind) ||
				ts.isNumericLiteral(node.literal)
			)
				return `z.literal(${node.literal.getText(file)})`;
			return fail(node);
		}
		if (ts.isUnionTypeNode(node)) return `z.union([${node.types.map(schema).join(", ")}])`;
		if (ts.isArrayTypeNode(node)) return `z.array(${schema(node.elementType)})`;
		if (ts.isTypeReferenceNode(node)) {
			const name = node.typeName.getText(file);
			const args = node.typeArguments ?? [];
			if (name === "Array" && args.length === 1) return `z.array(${schema(args[0])})`;
			// ts-rs uses this for an empty Rust request; JSON cannot have symbol keys.
			if (
				name === "Record" &&
				args.length === 2 &&
				args[0].kind === ts.SyntaxKind.SymbolKeyword &&
				args[1].kind === ts.SyntaxKind.NeverKeyword
			)
				return "z.object({})";
			if (args.length) return fail(node);
			return reference(name);
		}
		if (ts.isMappedTypeNode(node)) {
			if (
				node.typeParameter.constraint?.kind !== ts.SyntaxKind.StringKeyword ||
				node.nameType ||
				node.questionToken ||
				node.readonlyToken ||
				!node.type
			)
				return fail(node);
			return `z.record(z.string(), ${schema(node.type)})`;
		}
		if (ts.isTypeLiteralNode(node)) {
			const fields = node.members.map((member) => {
				if (
					!ts.isPropertySignature(member) ||
					!member.type ||
					!member.name ||
					(!ts.isIdentifier(member.name) && !ts.isStringLiteral(member.name)) ||
					member.modifiers?.length
				)
					return fail(member);
				const value = schema(member.type);
				return `${JSON.stringify(member.name.text)}: ${member.questionToken ? `z.optional(${value})` : value}`;
			});
			return `z.object({ ${fields.join(", ")} })`;
		}
		return fail(node);
	}
	for (const name of [...aliases.keys()].sort()) reference(name);
	return (
		"// Generated by schema-codegen from fttr-sdk types. Do not edit.\n" +
		'import * as z from "zod/mini";\nimport type * as wire from "./types";\n\n' +
		[...rendered]
			.map(
				([name, expression]) =>
					`export const ${name}Schema = ${expression} satisfies z.ZodMiniType<wire.${name}>;\n`,
			)
			.join("") +
		"\n// Both directions are checked: schema narrowing and contract widening fail compilation.\n" +
		"type Assert<T extends true> = T;\n" +
		"export type SchemaContracts = [\n" +
		[...rendered.keys()]
			.map(
				(name) =>
					`\tAssert<[z.infer<typeof ${name}Schema>] extends [wire.${name}] ? true : false>,\n\tAssert<[wire.${name}] extends [z.infer<typeof ${name}Schema>] ? true : false>,\n`,
			)
			.join("") +
		"];\n"
	);
}
