import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, "..");
const ICONS_JSON = resolve(REPO_ROOT, "node_modules/@iconify-json/fluent/icons.json");
const OUTPUT_PATH = resolve(REPO_ROOT, "src/view/topology/icons.ts");

const TOPOLOGY_ICON_MAP = {
	controller: "router-20-regular",
	onu: "connected-20-regular",
	wifiClient: "wifi-1-20-regular",
	wiredClient: "plug-connected-20-regular",
};

function toInlineSvg(icon, iconName) {
	if (!icon) {
		throw new Error(`Icon "${iconName}" not found in @iconify-json/fluent`);
	}
	const width = icon.width ?? 20;
	const height = icon.height ?? 20;
	const body = icon.body.replace(/\s*fill\s*=\s*(["']).*?\1/g, ' fill="currentColor"');
	return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" fill="none" aria-hidden="true">${body}</svg>`;
}

const collection = JSON.parse(readFileSync(ICONS_JSON, "utf8"));
const entries = Object.entries(TOPOLOGY_ICON_MAP).map(([key, iconName]) => {
	const svg = toInlineSvg(collection.icons[iconName], iconName);
	return `\t${key}: ${JSON.stringify(svg)},`;
});

const output = [
	"// SPDX-License-Identifier: Apache-2.0",
	"// Auto-generated by scripts/generate-icons.mjs from @iconify-json/fluent — do not edit manually.",
	"// biome-ignore format: generated file",
	"",
	"export const TOPOLOGY_ICONS = {",
	...entries,
	"} as const;",
	"",
	"export type TopologyIconName = keyof typeof TOPOLOGY_ICONS;",
	"",
].join("\n");

writeFileSync(OUTPUT_PATH, output, "utf8");
console.log(`Generated ${OUTPUT_PATH} (${entries.length} icons)`);
